def add(species, ability, profile, *rows):
    if species in SETS or len(rows) not in (1, 3):
        raise ValueError(f"Expected one or three sets for {species}")
    SETS[species] = tuple(common.FrontierSet(
        row[0], row[1], tuple(row[2].split()),
        row[3] if len(row) > 3 else profile,
        row[4] if len(row) > 4 else ability,
        row[5] if len(row) > 5 else None) for row in rows)


def alias(species, source):
    if species in SETS:
        raise ValueError(species)
    SETS[species] = SETS[source]



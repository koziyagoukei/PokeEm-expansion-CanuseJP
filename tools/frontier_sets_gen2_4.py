def target_species(entries):
    generator = common.get_generator()
    values, _ = generator.parse_species_constants()
    registered = {entry[1] for entry in entries}
    later = common.target_species(registered, values)
    families = {}
    for path in generator.SPECIES_INFO_DIR.glob("gen_*_families.h"):
        generation = int(path.name.split("_")[1])
        for species in re.findall(r"\[(SPECIES_[A-Z0-9_]+)\]", generator.read_text(path)):
            families[species.removeprefix("SPECIES_")] = generation
    boundary = next(end for label, _, _, end, _ in entries if label == "FRONTIER_MON_SUDOWOODO_3")
    return {
        species for _, species, start, _, _ in entries
        if start > boundary and values[f"SPECIES_{species}"] > values["SPECIES_SUDOWOODO"]
        and species != "SHEDINJA" and species not in later
        and (values["SPECIES_CHIKORITA"] <= values[f"SPECIES_{species}"] <= values["SPECIES_ARCEUS"]
             or families.get(species) in (2, 3, 4))
    } | {"SMEARGLE"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--audit", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    generator = common.get_generator()
    entries = common.read_entries(generator.read_text(generator.BATTLE_FRONTIER_MONS))
    registered = {entry[1] for entry in entries}
    required = target_species(entries)
    if SETS.keys() != required:
        raise ValueError(f"Missing: {sorted(required - SETS.keys())}; unexpected: {sorted(SETS.keys() - required)}")
    if sum(species == "SMEARGLE" for _, species, _, _, _ in entries) != 3:
        raise ValueError("Register the three appended Smeargle IDs before updating the pool")
    boundary = next(end for label, _, _, end, _ in entries if label == "FRONTIER_MON_SUDOWOODO_3")
    protected = {label: body for label, species, start, _, body in entries
                 if start < boundary or species == "SHEDINJA" or species not in SETS}
    common.validate_sets(registered | {"SMEARGLE"}, sets=SETS, required_species=required)
    changed = 0
    if not args.audit:
        changed = common.apply_curated_sets(generator.BATTLE_FRONTIER_MONS, check=args.check,
            sets=SETS, required_species=required)
        after = {entry[0]: entry[4] for entry in common.read_entries(generator.read_text(generator.BATTLE_FRONTIER_MONS))}
        if any(after[label] != body for label, body in protected.items()):
            raise ValueError("A protected or out-of-scope entry changed")
    print(f"Validated {len(SETS)} species/forms / {sum(map(len, SETS.values()))} active sets; updated {changed} entries.")


if __name__ == "__main__":
    main()




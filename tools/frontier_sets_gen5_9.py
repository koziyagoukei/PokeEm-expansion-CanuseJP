def read_entries(text: str) -> list[tuple[str, str, int, int, str]]:
    generator = get_generator()
    entries = []
    for match in re.finditer(r"\[(FRONTIER_MON_[A-Z0-9_]+_[123])\]\s*=\s*\{", text):
        start = text.index("{", match.start())
        end = generator.find_matching_brace(text, start) + 1
        body = text[start:end]
        species = re.search(r"\.species\s*=\s*SPECIES_([A-Z0-9_]+)", body)
        if species is None:
            raise ValueError(f"Missing species in {match.group(1)}")
        entries.append((match.group(1), species.group(1), start, end, body))
    return entries


def target_species(registered: set[str], values: dict[str, int]) -> set[str]:
    generator = get_generator()
    families = {}
    for path in generator.SPECIES_INFO_DIR.glob("gen_*_families.h"):
        generation = int(path.name.split("_")[1])
        for species in re.findall(r"\[(SPECIES_[A-Z0-9_]+)\]", generator.read_text(path)):
            families[species.removeprefix("SPECIES_")] = generation
    return {
        species for species in registered
        if families.get(species, 0) >= 5
        or values["SPECIES_VICTINI"] <= values[f"SPECIES_{species}"] <= values["SPECIES_ENAMORUS_INCARNATE"]
        or values["SPECIES_SPRIGATITO"] <= values[f"SPECIES_{species}"] <= values["SPECIES_PECHARUNT"]
        or any(region in species for region in ("_ALOLA", "_GALAR", "_HISUI", "_PALDEA"))
    }


def species_blocks() -> dict[str, str]:
    generator = get_generator()
    blocks = {}
    for path in generator.SPECIES_INFO_DIR.glob("gen_*_families.h"):
        text = generator.read_text(path)
        joined = text.replace("\\\n", " ")
        macros = {
            match.group(1): (match.group(2), match.group(3))
            for match in re.finditer(r"(?m)^\s*#define\s+([A-Z0-9_]+_INFO)(?:\(([^)]*)\))?\s+([^\n]+)", joined)
        }

        def expand(body: str) -> str:
            for _ in range(10):
                previous = body
                for name, (params, replacement) in macros.items():
                    if params is None:
                        body = re.sub(rf"\b{name}\b", lambda match: replacement, body)
                    else:
                        def substitute(match):
                            arguments = [argument.strip() for argument in match.group(1).split(",")]
                            result = replacement
                            for param, argument in zip(params.split(","), arguments):
                                result = re.sub(rf"\b{param.strip()}\b", lambda match: argument, result)
                            return result
                        body = re.sub(rf"\b{name}\(([^()]*)\)", substitute, body)
                if body == previous:
                    break
            return body

        for match in re.finditer(r"\[(SPECIES_[A-Z0-9_]+)\]\s*=\s*\{", text):
            start = text.index("{", match.start())
            blocks[match.group(1)] = expand(text[start:generator.find_matching_brace(text, start) + 1])
        for match in re.finditer(r"\[(SPECIES_[A-Z0-9_]+)\]\s*=\s*([A-Z0-9_]+_INFO\([^)]*\))", text):
            blocks[match.group(1)] = expand(match.group(2))
    return blocks


def read_learnsets() -> dict[str, set[str]]:
    generator = get_generator()
    learnsets = {species: set(moves) for species, moves in generator.parse_full_learnsets().items()}
    # Match the runtime form fallback for the event and Z-A additions as well.
    family_forms = {}
    blocks = species_blocks()
    for species, body in blocks.items():
        table = re.search(r"\.formSpeciesIdTable\s*=\s*(s[A-Za-z0-9_]+)", body)
        if table:
            family_forms[species] = table.group(1)
    forms_text = generator.read_text(generator.ROOT / "src/data/pokemon/form_species_tables.h")
    bases = {}
    for match in re.finditer(r"static const u16\s+(s[A-Za-z0-9_]+)\[\]\s*=\s*\{(.*?)\};", forms_text, re.S):
        members = re.findall(r"SPECIES_[A-Z0-9_]+", match.group(2))
        if members:
            bases[match.group(1)] = members[0]
    values, _ = generator.parse_species_constants()
    metadata = generator.parse_species_info(values, {})
    # The precomputed union omits PreEvoMoves. Keep legal inherited moves and
    # newly added Z-A moves from the checked-in, per-game source documents.
    source_moves = {}
    for path in (generator.ROOT / "tools/learnset_helpers/porymoves_files").glob("*.json"):
        for name, methods in json.loads(generator.read_text(path)).items():
            species = f"SPECIES_{name}"
            if species not in values:
                continue
            inherited = source_moves.setdefault(values[species], set())
            inherited.update(move["Move"] for move in methods.get("LevelMoves", []))
            for method in ("PreEvoMoves", "TMMoves", "EggMoves", "TutorMoves"):
                inherited.update(methods.get(method, []))
    for species in metadata:
        learnsets.setdefault(species, set()).update(source_moves.get(values[species], set()))
    # Each source has its own fallback. Do this before merging event arrays.
    for species in metadata:
        base = bases.get(family_forms.get(species, ""), species)
        if not learnsets.get(species) and base in learnsets:
            learnsets[species] = set(learnsets[base])
    tables = {}
    for path in sorted(generator.LEVEL_UP_DIR.glob("gen_*.h")):
        for match in re.finditer(r"static const struct LevelUpMove\s+(s[A-Za-z0-9_]+)\[\]\s*=\s*\{(.*?)\};", generator.read_text(path), re.S):
            tables.setdefault(match.group(1), set()).update(re.findall(r"MOVE_[A-Z0-9_]+", match.group(2)))
    for filename in ("teachable_learnsets.h", "egg_moves.h"):
        text = generator.read_text(generator.ROOT / "src/data/pokemon" / filename)
        for match in re.finditer(r"static const u16\s+(s[A-Za-z0-9_]+)\[\]\s*=\s*\{(.*?)\};", text, re.S):
            tables.setdefault(match.group(1), set()).update(re.findall(r"MOVE_[A-Z0-9_]+", match.group(2)))
    for filename in ("frontier_event_learnsets.h", "frontier_za_dlc_learnsets.h"):
        text = generator.read_text(generator.ROOT / "src/data/pokemon" / filename)
        arrays = {
            match.group(1): set(re.findall(r"MOVE_[A-Z0-9_]+", match.group(2)))
            for match in re.finditer(r"static const u16\s+(s[A-Za-z0-9_]+)\[\]\s*=\s*\{(.*?)\};", text, re.S)
        }
        extra = {
            species: arrays[table] for species, table in
            re.findall(r"\[(SPECIES_[A-Z0-9_]+)\]\s*=\s*(s[A-Za-z0-9_]+)", text)
        }
        for species in metadata:
            base = bases.get(family_forms.get(species, ""), species)
            learnsets.setdefault(species, set()).update(extra.get(species, extra.get(base, set())))
    for species, data in metadata.items():
        base = bases.get(family_forms.get(species, ""), species)
        for field in ("levelUpLearnset", "teachableLearnset", "eggMoveLearnset"):
            table = re.search(rf"\.{field}\s*=\s*(s[A-Za-z0-9_]+)", blocks.get(species, ""))
            if table:
                learnsets.setdefault(species, set()).update(tables.get(table.group(1), set()))
        # These two moves are explicitly universal in this project's Frontier tutor.
        learnsets[species].update(("MOVE_HIDDEN_POWER", "MOVE_TERA_BLAST"))
    form_changes = generator.read_text(generator.FORM_CHANGE_TABLES)
    for target, move in re.findall(r"\{FORM_CHANGE_BEGIN_BATTLE,\s*(SPECIES_[A-Z0-9_]+),\s*ITEM_[A-Z0-9_]+,\s*MOVE_[A-Z0-9_]+,\s*(MOVE_[A-Z0-9_]+)\}", form_changes):
        learnsets.setdefault(target, set()).add(move)
    for target, move in re.findall(r"\{\d+,\s*ITEM_[A-Z0-9_]+,\s*SPECIES_[A-Z0-9_]+,\s*SPECIES_[A-Z0-9_]+,\s*(SPECIES_[A-Z0-9_]+),\s*(MOVE_[A-Z0-9_]+),", form_changes):
        learnsets.setdefault(target, set()).add(move)
    # Appliance moves are assigned by the catalog, not ordinary learnsets.
    party_data = generator.read_text(generator.ROOT / "src/data/party_menu.h")
    for form, move in re.findall(r"#define ROTOM_(HEAT|WASH|FROST|FAN|MOW)_MOVE\s+(MOVE_[A-Z0-9_]+)", party_data):
        learnsets.setdefault(f"SPECIES_ROTOM_{form}", set()).add(move)
    # Match IsFrontierSketchMove: real PP and not sketchBanned.
    move_text = generator.read_text(generator.MOVE_INFO)
    sketch_moves = set()
    for match in re.finditer(r"\[(MOVE_[A-Z0-9_]+)\]\s*=\s*\{", move_text):
        start = move_text.index("{", match.start())
        body = move_text[start:generator.find_matching_brace(move_text, start) + 1]
        if generator.first_int(generator.get_move_field(body, "pp")) > 0 and not re.search(r"\.sketchBanned\s*=\s*TRUE", body):
            sketch_moves.add(match.group(1))
    learnsets.setdefault("SPECIES_SMEARGLE", set()).update(sketch_moves)
    aliases = dict(re.findall(r"\b(MOVE_[A-Z0-9_]+)\s*=\s*(MOVE_[A-Z0-9_]+)\b", generator.read_text(generator.ROOT / "include/constants/moves.h")))
    for moves in learnsets.values():
        for old_name, current_name in aliases.items():
            if old_name in moves:
                moves.add(current_name)
    return learnsets


def fields_for_set(set_data: FrontierSet, move_info) -> dict[str, str]:
    nature, evs = PROFILES[set_data.profile]
    moves = [f"MOVE_{move}" for move in set_data.moves]
    physical = any(
        move_info[move].category == "DAMAGE_CATEGORY_PHYSICAL"
        and move not in ("MOVE_BODY_PRESS", "MOVE_FOUL_PLAY", "MOVE_COUNTER")
        for move in moves
    )
    ivs = [31, 31 if physical else 0, 31, 31, 31, 31]
    slow = set_data.profile.startswith("TR") or "MOVE_GYRO_BALL" in moves
    if slow:
        ivs[3] = 0
    if "MOVE_HIDDEN_POWER" in moves:
        if set_data.hidden_power is None:
            raise ValueError("Hidden Power requires an explicit type")
        ivs = list((HIDDEN_POWER_SLOW_IVS if slow else HIDDEN_POWER_IVS)[set_data.hidden_power])
    return {
        "moves": "{" + ", ".join(moves) + "}",
        "heldItem": f"ITEM_{set_data.item}",
        "ev": "TRAINER_PARTY_EVS(" + ", ".join(map(str, evs)) + ")",
        "nature": f"NATURE_{nature}",
        "iv": "TRAINER_PARTY_IVS(" + ", ".join(map(str, ivs)) + ")",
        "ability": f"ABILITY_{set_data.ability}",
        "teraType": f"TYPE_{set_data.tera}",
    }


def validate_sets(registered: set[str], require_all: bool = True, *, sets=None, required_species=None) -> None:
    sets = SETS if sets is None else sets
    generator = get_generator()
    values, order = generator.parse_species_constants()
    species_info = generator.parse_species_info(values, order)
    blocks = species_blocks()
    moves_info = generator.parse_move_info()
    learnsets = read_learnsets()
    items = set(re.findall(r"ITEM_[A-Z0-9_]+", generator.read_text(generator.ROOT / "include/constants/items.h")))
    types = set(re.findall(r"TYPE_[A-Z0-9_]+", generator.read_text(generator.ROOT / "include/constants/pokemon.h")))
    mega_items = generator.parse_mega_stones_by_form_table()
    signatures = generator.parse_signature_z_moves()
    crystals = {item: type_ for type_, item in generator.Z_CRYSTALS_BY_TYPE.items()}
    all_mega_items = {item for stones in mega_items.values() for item in stones}
    errors = []
    if require_all:
        required = target_species(registered, values) if required_species is None else required_species
        for species in sorted(required - sets.keys()):
            errors.append(f"{species}: no curated sets")
    for species in sorted(registered & sets.keys()):
        data = species_info[f"SPECIES_{species}"]
        variants = sets[species]
        if len(variants) not in (1, 3) or len({(tuple(variant.moves), variant.hidden_power) for variant in variants}) != len(variants):
            errors.append(f"{species}: expected one or three distinct move sets")
        for slot, variant in enumerate(variants, 1):
            prefix = f"{species}_{slot}"
            item = f"ITEM_{variant.item}"
            moves = [f"MOVE_{move}" for move in variant.moves]
            if len(moves) != 4 or len(set(moves)) != 4:
                errors.append(f"{prefix}: expected four distinct moves")
            for move in moves:
                if move not in moves_info:
                    errors.append(f"{prefix}: undefined {move}")
                elif move not in learnsets.get(data.species, set()):
                    errors.append(f"{prefix}: cannot learn {move}")
            if item not in items:
                errors.append(f"{prefix}: undefined {item}")
            if f"TYPE_{variant.tera}" not in types or variant.tera in ("MYSTERY", "NORMAL"):
                errors.append(f"{prefix}: unavailable Tera type {variant.tera}")
            ability_field = re.search(r"\.abilities\s*=\s*\{([^}]*)\}", blocks.get(data.species, ""))
            abilities = re.findall(r"ABILITY_[A-Z0-9_]+", ability_field.group(1)) if ability_field else data.abilities
            if f"ABILITY_{variant.ability}" not in abilities:
                errors.append(f"{prefix}: invalid ability {variant.ability}")
            statuses = [move for move in moves if move in moves_info and moves_info[move].category == "DAMAGE_CATEGORY_STATUS"]
            if item == "ITEM_ASSAULT_VEST" and statuses:
                errors.append(f"{prefix}: Assault Vest with {statuses}")
            if item.startswith("ITEM_CHOICE_"):
                incompatible = set(statuses) - {"MOVE_TRICK", "MOVE_SWITCHEROO", "MOVE_HEALING_WISH", "MOVE_MEMENTO", "MOVE_PARTING_SHOT"}
                if incompatible:
                    errors.append(f"{prefix}: Choice item with {sorted(incompatible)}")
            if item in crystals and not any(move in moves_info and moves_info[move].type == crystals[item] for move in moves):
                errors.append(f"{prefix}: Z crystal has no matching move")
            if item.endswith("IUM_Z") and item not in crystals:
                if item == "ITEM_ULTRANECROZIUM_Z":
                    valid_signature = species in ("NECROZMA_DUSK_MANE", "NECROZMA_DAWN_WINGS") and "MOVE_PHOTON_GEYSER" in moves
                else:
                    valid_signature = signatures.get(data.species, (None, None)) == (item, next((move for move in moves if signatures.get(data.species, (None, None))[1] == move), None))
                if not valid_signature:
                    errors.append(f"{prefix}: invalid signature Z crystal")
            if item in all_mega_items and item not in mega_items.get(data.form_change_table or "", []):
                errors.append(f"{prefix}: Mega stone does not match species")
            if "MOVE_TERA_BLAST" in moves and (item in all_mega_items or item.endswith("IUM_Z")):
                errors.append(f"{prefix}: Tera-only coverage conflicts with the held gimmick item")
            if "MOVE_ACROBATICS" in moves and item not in {"ITEM_FLYING_GEM", "ITEM_WHITE_HERB", "ITEM_BOOSTER_ENERGY"}:
                errors.append(f"{prefix}: Acrobatics cannot reliably reach full power")
            if item == "ITEM_LOADED_DICE" and not set(moves) & (generator.MULTI_HIT_MOVES | {"MOVE_PIN_MISSILE"}):
                errors.append(f"{prefix}: Loaded Dice without a supported multi-hit move")
            if item == "ITEM_POWER_HERB" and not set(moves) & {"MOVE_GEOMANCY", "MOVE_METEOR_BEAM", "MOVE_ELECTRO_SHOT", "MOVE_SOLAR_BEAM", "MOVE_SKY_ATTACK", "MOVE_SOLAR_BLADE", "MOVE_FREEZE_SHOCK"}:
                errors.append(f"{prefix}: Power Herb without a charge move")
            if "MOVE_HIDDEN_POWER" in moves and variant.hidden_power not in HIDDEN_POWER_IVS:
                errors.append(f"{prefix}: Hidden Power type is missing")
            if any(move in ("MOVE_HEAL_PULSE", "MOVE_HELPING_HAND", "MOVE_FOLLOW_ME", "MOVE_INSTRUCT", "MOVE_ALLY_SWITCH", "MOVE_AFTER_YOU") for move in moves):
                errors.append(f"{prefix}: doubles-only support move in the shared singles pool")
            nature, evs = PROFILES[variant.profile]
            if sum(evs) != 508 or any(ev < 0 or ev > 252 for ev in evs):
                errors.append(f"{prefix}: invalid EV spread {evs}")
            if all(move in moves_info for move in moves):
                damage = [moves_info[move] for move in moves if moves_info[move].category != "DAMAGE_CATEGORY_STATUS" and move not in ("MOVE_BODY_PRESS", "MOVE_FOUL_PLAY", "MOVE_COUNTER", "MOVE_MIRROR_COAT", "MOVE_NIGHT_SHADE")]
                if damage and all(move.category == "DAMAGE_CATEGORY_SPECIAL" for move in damage) and evs[1]:
                    errors.append(f"{prefix}: Attack EVs with only special attacks")
                if damage and all(move.category == "DAMAGE_CATEGORY_PHYSICAL" for move in damage) and evs[4]:
                    errors.append(f"{prefix}: Sp. Atk EVs with only physical attacks")
    if errors:
        raise ValueError("\n".join(errors))


def apply_curated_sets(path: Path, *, require_all: bool = True, check: bool = False, sets=None, required_species=None) -> int:
    sets = SETS if sets is None else sets
    generator = get_generator()
    original = generator.read_text(path)
    entries = read_entries(original)
    registered = {entry[1] for entry in entries}
    validate_sets(registered, require_all, sets=sets, required_species=required_species)
    move_info = generator.parse_move_info()
    replacements = []
    changed = 0
    for label, species, start, end, body in entries:
        if species not in sets:
            continue
        variants = sets[species]
        variant = variants[min(int(label[-1]) - 1, len(variants) - 1)]
        expected = fields_for_set(variant, move_info)
        updated = body
        for field, value in expected.items():
            pattern = rf"(?m)^([ \t]*)\.{field}\s*=\s*[^\n]+"
            match = re.search(pattern, updated)
            if match is None:
                raise ValueError(f"Missing {field} in {label}")
            updated = re.sub(pattern, lambda match: f"{match.group(1)}.{field} = {value},", updated, count=1)
        if updated != body:
            changed += 1
            replacements.append((start, end, updated))
    if check and changed:
        raise ValueError(f"{changed} registered sets differ from their curated definitions")
    if not check:
        for start, end, updated in reversed(replacements):
            original = original[:start] + updated + original[end:]
        if changed:
            path.write_text(original, encoding="utf-8", newline="\n")
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--audit", action="store_true", help="Validate the proposed sets without changing files")
    mode.add_argument("--check", action="store_true", help="Also check that the header matches")
    mode.add_argument("--write", action="store_true", help="Apply the curated fields to the existing header")
    args = parser.parse_args()
    generator = get_generator()
    registered = {entry[1] for entry in read_entries(generator.read_text(generator.BATTLE_FRONTIER_MONS))}
    if args.audit:
        validate_sets(registered)
        changed = 0
    else:
        changed = apply_curated_sets(generator.BATTLE_FRONTIER_MONS, check=args.check)
    count = len(registered & SETS.keys())
    print(f"Validated {count} species / {count * 3} sets; updated {changed} sets.")


if __name__ == "__main__":
    main()


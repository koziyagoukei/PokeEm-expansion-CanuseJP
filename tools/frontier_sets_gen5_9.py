@dataclass(frozen=True)
class FrontierSet:
    item: str
    tera: str
    moves: tuple[str, ...]
    profile: str
    ability: str
    hidden_power: str | None = None


SETS: dict[str, tuple[FrontierSet, ...]] = {}


def add(species: str, ability: str, profile: str, *rows: tuple[str, ...]) -> None:
    if species in SETS or len(rows) != 3:
        raise ValueError(f"Expected three unique sets for {species}")
    SETS[species] = tuple(
        FrontierSet(row[0], row[1], tuple(row[2].split()),
                    row[3] if len(row) > 3 else profile,
                    row[4] if len(row) > 4 else ability,
                    row[5] if len(row) > 5 else None)
        for row in rows
    )


def alias(species: str, source: str) -> None:
    if species in SETS:
        raise ValueError(f"Duplicate species: {species}")
    SETS[species] = SETS[source]



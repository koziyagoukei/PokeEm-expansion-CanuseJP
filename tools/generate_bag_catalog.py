#!/usr/bin/env python3
"""Size the ordinary pocket from Frontier/resort acquisition sources."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ITEM_RE = re.compile(r"\bITEM_[A-Z0-9_]+\b")
ARRAYS = {
    "src/frontier_creator.c": (
        "sFrontierHubAutoItems", "sFrontierHubGiveItems", "sFrontierMintGiveItems",
        "sFrontierHubInitialGiftMonPairs", "sFrontierHubInitialRayquaza",
    ),
    "src/battle_script_commands.c": ("sPickupTable",),
    "src/contest_shop.c": ("sScarfItems",),
    "src/player_pc.c": ("sNewGamePCItems",),
}
MAP_PREFIXES = (
    "BattleFrontier_", "Party", "party", "ultra", "MiniMiniVilla",
    "ContestHall", "LilycoveCity_Contest",
)


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


def without_comments(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def array_body(text, name):
    match = re.search(r"\b" + re.escape(name) + r"\s*(?:\[[^;]*?)?=\s*\{", text)
    if match is None:
        raise ValueError("missing acquisition array: " + name)
    start = match.end()
    depth = 1
    for end in range(start, len(text)):
        if text[end] == "{":
            depth += 1
        elif text[end] == "}":
            depth -= 1
            if depth == 0:
                return text[start:end]
    raise ValueError("unterminated acquisition array: " + name)


def item_pockets():
    text = read("src/data/items.h")
    entries = re.split(r"(?m)^    \[(ITEM_\w+)\] =\n", text)
    result = {}
    for i in range(1, len(entries), 2):
        pocket = re.search(r"\.pocket\s*=\s*(POCKET_\w+)", entries[i + 1])
        if pocket:
            result[entries[i]] = pocket[1]
    return result


def collect():
    origins = {}

    def add(text, origin):
        for item in ITEM_RE.findall(without_comments(text)):
            if item != "ITEM_NONE":
                origins.setdefault(item, set()).add(origin)

    for path, names in ARRAYS.items():
        text = read(path)
        for name in names:
            add(array_body(text, name), path + ":" + name)

    # These sources contain only shop stock, starter inventory or script gifts.
    for path in (
        "src/frontier_inventory.c",
        "src/data/frontier_intro.h",
    ):
        add(read(path), path)
    add("ITEM_HONEY", "src/battle_script_commands.c:Honey Gather")
    if re.search(r"^#define\s+P_SHUCKLE_BERRY_JUICE\s+GEN_2\b", read("include/config/pokemon.h"), re.M):
        add("ITEM_BERRY_JUICE", "src/battle_script_commands.c:Shuckle")
    for directory in sorted((ROOT / "data/maps").iterdir()):
        if directory.is_dir() and directory.name.startswith(MAP_PREFIXES):
            for name in ("scripts.inc", "map.json"):
                path = directory / name
                if path.exists():
                    add(path.read_text(encoding="utf-8"), path.relative_to(ROOT).as_posix())

    pockets = item_pockets()
    unknown = set(origins) - pockets.keys()
    if unknown:
        raise ValueError("unrecognized item constants: " + ", ".join(sorted(unknown)))
    items = [
        {"item": item, "sources": sorted(sources)}
        for item, sources in sorted(origins.items())
        if pockets[item] == "POCKET_ITEMS"
    ]
    if not 0 < len(items) < 255:
        raise ValueError("ordinary bag list must fit existing 8-bit UI counters")
    return items


def outputs(items):
    count = len(items)
    return {
        "include/constants/frontier_bag.h": (
            "// Generated by tools/generate_bag_catalog.py.\n"
            "#ifndef GUARD_CONSTANTS_FRONTIER_BAG_H\n"
            "#define GUARD_CONSTANTS_FRONTIER_BAG_H\n\n"
            f"#define FRONTIER_OBTAINABLE_ITEMS_COUNT {count}\n\n"
            "#endif\n"
        ),
        "test/data/frontier_bag_items.h": (
            "// Generated by tools/generate_bag_catalog.py.\n"
            "static const enum Item sFrontierObtainableItems[] =\n{\n"
            + "".join("    " + item["item"] + ",\n" for item in items)
            + "};\n"
        ),
        "tools/data/frontier_bag_catalog.json": json.dumps(
            {"ordinary_item_count": count, "items": items}, indent=2, sort_keys=True
        ) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    items = collect()
    failed = []
    for name, content in outputs(items).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                failed.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if failed:
        parser.error("regenerate bag catalog: " + ", ".join(failed))
    print(f"Frontier ordinary bag: {len(items)} obtainable item types; catalog validated")


if __name__ == "__main__":
    main()
